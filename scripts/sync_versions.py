#!/usr/bin/env python3
"""
sync_versions.py — version-integrity stamper for Nova Download Manager.

version.json (repo root) is the SINGLE SOURCE OF TRUTH.
This script stamps every version surface from it:

  surface                                   | direction
  ------------------------------------------+------------------------------
  Directory.Build.props  <Version>          | engine/app assemblies
  src/Nova.Domain/VersionInfo.cs            | GENERATED — C# constants
  apps/nova_desktop/pubspec.yaml            | version: X.Y.Z+build
  apps/nova_desktop/lib/core/build_version.dart | GENERATED — Dart constants
  extensions/chromium/manifest.json         | "version"
  extensions/firefox/manifest.json          | "version"
  installer/nova-installer.iss               | #define MyAppVersion

Cross-checks (fail on mismatch):
  * version.json dbSchema  == highest migration in src/Nova.Persistence/NovaDatabase.cs
  * version.json protocol.ipc == Protocol.Version in src/Nova.Ipc/Protocol.cs
  * no stale 'nova-(chromium|firefox)-<literal-version>' zip names in .github/workflows

Usage:
  python3 scripts/sync_versions.py            # stamp everything
  python3 scripts/sync_versions.py --check    # verify only; exit 1 on drift (CI gate)
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

PROPS = ROOT / "Directory.Build.props"
VERSIONINFO_CS = ROOT / "src/Nova.Domain/VersionInfo.cs"
PUBSPEC = ROOT / "apps/nova_desktop/pubspec.yaml"
BUILD_VERSION_DART = ROOT / "apps/nova_desktop/lib/core/build_version.dart"
EXT_MANIFESTS = [
    ROOT / "extensions/chromium/manifest.json",
    ROOT / "extensions/firefox/manifest.json",
]
EXT_MIN_ENGINE_TS = ROOT / "extensions/shared/protocol.ts"
EXT_MIN_ENGINE_JS = ROOT / "extensions/shared/ui/options.js"
INSTALLER_ISS = ROOT / "installer/nova-installer.iss"
NOVA_DATABASE_CS = ROOT / "src/Nova.Persistence/NovaDatabase.cs"
PROTOCOL_CS = ROOT / "src/Nova.Ipc/Protocol.cs"
WORKFLOWS_DIR = ROOT / ".github/workflows"


def load_ssot() -> dict:
    data = json.loads((ROOT / "version.json").read_text(encoding="utf-8"))
    for key in ("product", "version", "channel", "build", "dbSchema"):
        if key not in data:
            raise SystemExit(f"version.json: missing required key '{key}'")
    for comp in ("engine", "app", "extensionChromium", "extensionFirefox"):
        if comp not in data.get("components", {}):
            raise SystemExit(f"version.json: missing components.{comp}")
    if "ipc" not in data.get("protocol", {}):
        raise SystemExit("version.json: missing protocol.ipc")
    if "engineForExtension" not in data.get("minimums", {}):
        raise SystemExit("version.json: missing minimums.engineForExtension")
    return data


# ---------------------------------------------------------------- generated files

VERSIONINFO_TEMPLATE = """// <auto-generated>
// Generated by scripts/sync_versions.py from version.json — DO NOT EDIT BY HAND.
// Single source of truth: version.json at the repository root.
// CI (version-audit) fails the build if any surface drifts from it.
// </auto-generated>

namespace Nova.Domain;

/// <summary>
/// Central version constants for the whole product. Every place that needs a
/// version string/number reads it from here (or from the assembly version,
/// which is stamped from the same source at build time).
/// </summary>
public static class VersionInfo
{{
    public const string Product = "{product}";

    /// <summary>SemVer product version — engine, app and extensions are released in lockstep.</summary>
    public const string Version = "{version}";

    /// <summary>Release channel: dev | beta | stable.</summary>
    public const string Channel = "{channel}";

    /// <summary>Monotonic build number (Flutter pubspec '+N').</summary>
    public const int Build = {build};

    /// <summary>IPC wire protocol (mirrors Nova.Ipc.Protocol.Version; cross-checked by CI).</summary>
    public const int IpcProtocol = {ipc};

    /// <summary>SQLite schema version (mirrors the latest NovaDatabase migration; cross-checked by CI).</summary>
    public const int DbSchema = {db_schema};

    /// <summary>Minimum engine version the browser extensions require (runtime compat banner).</summary>
    public const string MinEngineForExtension = "{min_engine}";

    /// <summary>HTTP User-Agent for every outbound engine request.</summary>
    public const string UserAgent = "{user_agent}";

    /// <summary>BitTorrent extension-handshake v-string (BEP-10).</summary>
    public const string PeerWireClient = "Nova DM {version}";
}}
"""

BUILD_VERSION_TEMPLATE = """// GENERATED by scripts/sync_versions.py from version.json — DO NOT EDIT.
// Single source of truth: version.json at the repository root.

class BuildVersion {{
  static const product = '{product}';
  static const version = '{version}';
  static const channel = '{channel}';
  static const build = {build};
}}
"""


def gen_versioninfo(v: dict) -> str:
    return VERSIONINFO_TEMPLATE.format(
        product=v["product"],
        version=v["version"],
        channel=v["channel"],
        build=v["build"],
        ipc=v["protocol"]["ipc"],
        db_schema=v["dbSchema"],
        min_engine=v["minimums"]["engineForExtension"],
        user_agent=v.get("userAgent", f"NovaDownloadManager/{v['version']}"),
    )


def gen_build_version_dart(v: dict) -> str:
    return BUILD_VERSION_TEMPLATE.format(
        product=v["product"], version=v["version"], channel=v["channel"], build=v["build"]
    )


# ---------------------------------------------------------------- regex stampers

def stamp_regex(path: Path, pattern: str, repl: str, check: bool) -> tuple[bool, str]:
    text = path.read_text(encoding="utf-8")
    new, n = re.subn(pattern, repl, text, count=1)
    if n == 0:
        raise SystemExit(f"sync_versions: pattern not found in {path}:\n  {pattern}")
    if new != text:
        if not check:
            path.write_text(new, encoding="utf-8")
        return False, f"STAMPED {path.name}: {repl.strip()}"
    return True, f"ok       {path.name}"


def stamp_json_field(path: Path, field: str, value: str, check: bool) -> tuple[bool, str]:
    text = path.read_text(encoding="utf-8")
    pattern = rf'("{field}"\s*:\s*")[^"]+(")'
    new, n = re.subn(pattern, rf"\g<1>{value}\g<2>", text, count=1)
    if n == 0:
        raise SystemExit(f"sync_versions: field '{field}' not found in {path}")
    if new != text:
        if not check:
            path.write_text(new, encoding="utf-8")
        return False, f"STAMPED {path.parent.name}/{path.name}: {field}={value}"
    return True, f"ok       {path.parent.name}/{path.name}"


def write_generated(path: Path, content: str, check: bool) -> tuple[bool, str]:
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return True, f"ok       {path.name} (generated)"
    if not check:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    return False, f"STAMPED {path.name} (generated)"


# ---------------------------------------------------------------- cross-checks

def latest_migration() -> int:
    text = NOVA_DATABASE_CS.read_text(encoding="utf-8")
    versions = [int(m) for m in re.findall(r"RunMigration\((\d+),", text)]
    legacy = [int(m) for m in re.findall(r"SchemaVersion = (\d+);", text)]
    all_v = versions + legacy
    if not all_v:
        raise SystemExit("sync_versions: no migrations found in NovaDatabase.cs")
    return max(all_v)


def protocol_version() -> int:
    text = PROTOCOL_CS.read_text(encoding="utf-8")
    m = re.search(r"const int Version\s*=\s*(\d+)", text)
    if not m:
        raise SystemExit("sync_versions: Protocol.Version not found")
    return int(m.group(1))


def workflow_stale_literals() -> list[str]:
    """Any hardcoded 'nova-chromium-1.6.0.zip'-style literal is a drift bug — must use wildcards."""
    stale = []
    if WORKFLOWS_DIR.is_dir():
        for wf in WORKFLOWS_DIR.glob("*.yml"):
            for m in re.findall(r"nova-(?:chromium|firefox|dm|engine|setup)-\d+\.\d+\.\d+", wf.read_text(encoding="utf-8")):
                stale.append(f"{wf.name}: {m}")
    return stale


# ---------------------------------------------------------------- main

def main() -> int:
    check = "--check" in sys.argv
    v = load_ssot()
    ver, build = v["version"], v["build"]
    results: list[tuple[bool, str]] = []
    failures: list[str] = []

    # 1) Directory.Build.props (assembly Version for every C# project)
    results.append(stamp_regex(
        PROPS, r"(?<=<Version>)[^<]+", ver, check))

    # 2) generated C# constants
    results.append(write_generated(VERSIONINFO_CS, gen_versioninfo(v), check))

    # 3) Flutter pubspec (version: X.Y.Z+build) + generated Dart constants
    results.append(stamp_regex(
        PUBSPEC, r"(?m)^version:\s*\S+$", f"version: {ver}+{build}", check))
    results.append(write_generated(BUILD_VERSION_DART, gen_build_version_dart(v), check))

    # 4) extension source manifests (dist/ is regenerated by build.mjs from these)
    for m in EXT_MANIFESTS:
        results.append(stamp_json_field(m, "version", v["components"][
            "extensionChromium" if "chromium" in m.parts else "extensionFirefox"], check))

    # 5) Inno Setup installer
    results.append(stamp_regex(
        INSTALLER_ISS, r'(?<=#define MyAppVersion ")[^"]+', ver, check))

    # 5c) extension tooling package.json (private, but stamped for uniformity)
    results.append(stamp_json_field(
        ROOT / "extensions/package.json", "version", ver, check))

    # 5b) extension minimum-engine constants (TS + options-page JS)
    results.append(stamp_regex(
        EXT_MIN_ENGINE_TS, r"(?<=export const MIN_ENGINE_VERSION = ')[^']+", v["minimums"]["engineForExtension"], check))
    results.append(stamp_regex(
        EXT_MIN_ENGINE_JS, r"(?<=const MIN_ENGINE_VERSION = ')[^']+", v["minimums"]["engineForExtension"], check))

    # 6) cross-check: db schema vs NovaDatabase migrations
    db_latest = latest_migration()
    if db_latest != v["dbSchema"]:
        failures.append(
            f"dbSchema drift: version.json={v['dbSchema']} but NovaDatabase.cs latest migration={db_latest} "
            "(bump dbSchema in version.json when adding a migration)")

    # 7) cross-check: IPC protocol vs Protocol.cs
    proto = protocol_version()
    if proto != v["protocol"]["ipc"]:
        failures.append(
            f"protocol drift: version.json protocol.ipc={v['protocol']['ipc']} "
            f"but Protocol.Version={proto}")

    # 8) workflows must not hardcode versioned artifact names
    for s in workflow_stale_literals():
        failures.append(f"hardcoded artifact literal in workflow (use a wildcard): {s}")

    print(f"Nova version sync — SSOT version.json: {ver} (channel {v['channel']}, build {build})")
    for ok, line in results:
        print(f"  [{'PASS' if ok else check and 'DRIFT' or 'WRITE'}] {line}")
    for f in failures:
        print(f"  [FAIL] {f}")

    if check:
        drifted = [line for ok, line in results if not ok]
        if drifted or failures:
            print(f"\nVERSION AUDIT FAILED — {len(drifted)} drifted surface(s), {len(failures)} cross-check failure(s).")
            print("Fix: edit version.json, then run: python3 scripts/sync_versions.py")
            return 1
        print("\nVERSION AUDIT PASSED — all surfaces match version.json.")
        return 0

    if failures:
        print("\nCross-check failures remain — fix before committing.")
        return 1
    print("\nAll surfaces stamped from version.json.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
